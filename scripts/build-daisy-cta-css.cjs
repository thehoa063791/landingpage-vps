// Builds the daisyUI card, button and badge CSS used by lesson CTAs, for the learner app and
// the admin preview, so both render the same cards. Classes are renamed dz-* so they never meet
// other classes of the funnels; the tokens are daisyUI's "light" theme, set on .dz-theme.
// node scripts/build-daisy-cta-css.cjs   (downloads daisyUI from jsDelivr, MIT License)
const fs = require('fs');
const path = require('path');

const VERSION = '5.0.43';
const OUTPUTS = ['pages/dong-tien/src/styles/daisy-cta.css', 'src/admin/daisy-cta.css'].map(file => path.join(__dirname, '..', file));

// `@layer utilities { … }` would lose to unlayered rules such as the admin's button reset.
function unwrapLayers(css) {
  let out = '', i = 0;
  while (i < css.length) {
    const start = css.indexOf('@layer', i);
    if (start < 0) { out += css.slice(i); break; }
    const open = css.indexOf('{', start);
    out += css.slice(i, start);
    let depth = 1, j = open + 1;
    for (; j < css.length && depth; j++) depth += css[j] === '{' ? 1 : css[j] === '}' ? -1 : 0;
    out += css.slice(open + 1, j - 1);
    i = j;
  }
  return out;
}

async function main() {
  let css = '';
  for (const name of ['card', 'button', 'badge']) {
    const response = await fetch(`https://cdn.jsdelivr.net/npm/daisyui@${VERSION}/components/${name}.css`);
    if (!response.ok) throw new Error(`daisyUI ${name}.css: HTTP ${response.status}`);
    css += unwrapLayers((await response.text()).replace(/\/\*![^*]*\*\//g, '')) + '\n';
  }
  css = css.replace(/\.(card|btn|badge|image-full)(?![a-zA-Z0-9_])/g, '.dz-$1')
    .replace(/\.(card|btn|badge)-/g, '.dz-$1-')
    .replace(/\\:(card|btn|badge)/g, '\\:dz-$1');
  const header = `/*! daisyUI ${VERSION} card, button and badge (MIT License, https://daisyui.com), classes renamed dz-*.
   Generated by scripts/build-daisy-cta-css.cjs; do not edit by hand. */
.dz-theme {
  --color-base-100: oklch(100% 0 0); --color-base-200: oklch(98% 0 0); --color-base-300: oklch(95% 0 0); --color-base-content: oklch(21% .006 285.885);
  --color-primary: oklch(45% .24 277.023); --color-primary-content: oklch(93% .034 272.788);
  --color-secondary: oklch(65% .241 354.308); --color-secondary-content: oklch(94% .028 342.258);
  --color-accent: oklch(77% .152 181.912); --color-accent-content: oklch(38% .063 188.416);
  --color-neutral: oklch(14% .005 285.823); --color-neutral-content: oklch(92% .004 286.32);
  --color-info: oklch(74% .16 232.661); --color-info-content: oklch(29% .066 243.157);
  --color-success: oklch(76% .177 163.223); --color-success-content: oklch(37% .077 168.94);
  --color-warning: oklch(82% .189 84.429); --color-warning-content: oklch(41% .112 45.904);
  --color-error: oklch(71% .194 13.428); --color-error-content: oklch(27% .105 12.094);
  --radius-selector: .5rem; --radius-field: .25rem; --radius-box: .5rem; --size-selector: .25rem; --size-field: .25rem;
  --border: 1px; --depth: 1; --noise: 0; --fx-noise: none;
  color: var(--color-base-content); color-scheme: light;
}
`;
  // The admin has no Tailwind preflight, which daisyUI expects; a scoped copy of the parts it needs.
  const preflight = `.dz-theme :where(*, ::before, ::after) { margin: 0; padding: 0; border: 0 solid; box-sizing: border-box; }
.dz-theme :where(img, svg) { display: block; max-width: 100%; }
.dz-theme :where(h1, h2, h3, h4) { font-size: inherit; font-weight: inherit; }
.dz-theme :where(ul) { list-style: none; }
.dz-theme :where(button) { background: transparent; color: inherit; font: inherit; }
`;
  // Learner app: in Tailwind's components layer, so utilities on the markup (as in daisyUI's
  // examples) still win. Admin: no Tailwind, unlayered with the preflight above.
  for (const out of OUTPUTS) {
    const admin = out.includes(`${path.sep}admin${path.sep}`);
    fs.writeFileSync(out, header + (admin ? preflight + css.trim() : `@layer components {\n${css.trim()}\n}`) + '\n');
  }
  console.log(`daisyUI ${VERSION}: ${OUTPUTS.length} files, ${css.length} bytes`);
}
main().catch(error => { console.error(error.message); process.exit(1); });
